// Command generate snapshots GitHub mutation metadata without a runtime schema dependency.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/vektah/gqlparser/v2/ast"
	"github.com/vektah/gqlparser/v2/parser"
)

const publicSchemaURL = "https://docs.github.com/public/fpt/schema.docs.graphql"

type schemaInputField struct {
	Name string
	Type string
}

type schemaIDField struct {
	Name string
	Kind string
}

type mutationSchema struct {
	InputType         string
	InputFields       []schemaInputField
	IDFields          []schemaIDField
	PrimaryID         string
	Description       string
	Deprecated        bool
	DeprecationReason string
}

func main() {
	schemaPath := flag.String("schema", "", "local schema file; empty fetches the public GitHub schema")
	date := flag.String("date", "", "explicit schema snapshot date (YYYY-MM-DD)")
	output := flag.String("output", "schema_mutations.go", "generated Go file")
	expectedSHA := flag.String("sha256", "", "required raw schema SHA256; empty prints the fetched hash")
	flag.Parse()
	if err := generate(*schemaPath, *date, *output, *expectedSHA); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(schemaPath, date, output, expectedSHA string) error {
	if _, err := time.Parse("2006-01-02", date); err != nil {
		return fmt.Errorf("snapshot date must be explicit YYYY-MM-DD: %w", err)
	}
	data, err := readSchema(schemaPath)
	if err != nil {
		return err
	}
	digest := fmt.Sprintf("%x", sha256.Sum256(data))
	if expectedSHA != "" && !strings.EqualFold(expectedSHA, digest) {
		return fmt.Errorf("schema SHA256 mismatch: expected %s, got %s", expectedSHA, digest)
	}
	mutations, err := extractMutations(data)
	if err != nil {
		return err
	}
	var names []string
	for name := range mutations {
		names = append(names, name)
	}
	sort.Strings(names)
	var generated bytes.Buffer
	fmt.Fprintln(&generated, "// Code generated by go run ./generate; DO NOT EDIT.")
	fmt.Fprintln(&generated, "// Source: "+publicSchemaURL)
	fmt.Fprintln(&generated, "// Snapshot: "+date)
	fmt.Fprintln(&generated, "// SHA256: "+digest)
	fmt.Fprint(&generated, "\npackage graphql\n\n")
	fmt.Fprintf(&generated, "const schemaSnapshotDate = %q\n", date)
	fmt.Fprintf(&generated, "const schemaSnapshotSHA256 = %q\n\n", digest)
	fmt.Fprintln(&generated, "var schemaMutations = map[string]mutationSchema{")
	inputCount, candidateCount := 0, 0
	for _, name := range names {
		mutation := mutations[name]
		inputCount += len(mutation.InputFields)
		candidateCount += len(mutation.IDFields)
		fmt.Fprintf(&generated, "\t%q: {InputType: %q,\n", name, mutation.InputType)
		if len(mutation.InputFields) > 0 {
			fmt.Fprintln(&generated, "\t\tInputFields: []schemaInputField{")
			for _, field := range mutation.InputFields {
				fmt.Fprintf(&generated, "\t\t\t{Name: %q, Type: %q},\n", field.Name, field.Type)
			}
			fmt.Fprintln(&generated, "\t\t},")
		}
		if len(mutation.IDFields) > 0 {
			fmt.Fprintln(&generated, "\t\tIDFields: []schemaIDField{")
			for _, field := range mutation.IDFields {
				fmt.Fprintf(&generated, "\t\t\t{Name: %q, Kind: %q},\n", field.Name, field.Kind)
			}
			fmt.Fprintln(&generated, "\t\t},")
		}
		fmt.Fprintf(&generated, "\t\tPrimaryID: %q, Description: %q, Deprecated: %t, DeprecationReason: %q},\n", mutation.PrimaryID, mutation.Description, mutation.Deprecated, mutation.DeprecationReason)
	}
	fmt.Fprintln(&generated, "}")
	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		return fmt.Errorf("format snapshot: %w", err)
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		return fmt.Errorf("write snapshot: %w", err)
	}
	fmt.Printf("wrote %d mutations, %d input fields, %d ID candidates to %s (snapshot %s, SHA256 %s)\n", len(names), inputCount, candidateCount, output, date, digest)
	return nil
}

func extractMutations(data []byte) (map[string]mutationSchema, error) {
	document, err := parser.ParseSchema(&ast.Source{Name: publicSchemaURL, Input: string(data)})
	if err != nil {
		return nil, fmt.Errorf("parse schema: %w", err)
	}
	mutationType := "Mutation"
	for _, schemas := range []ast.SchemaDefinitionList{document.Schema, document.SchemaExtension} {
		for _, schema := range schemas {
			for _, operation := range schema.OperationTypes {
				if operation.Operation == ast.Mutation {
					mutationType = operation.Type
				}
			}
		}
	}
	definitions := make(map[string][]*ast.Definition)
	kinds := make(map[string]bool)
	for _, list := range []ast.DefinitionList{document.Definitions, document.Extensions} {
		for _, definition := range list {
			definitions[definition.Name] = append(definitions[definition.Name], definition)
			if definition.IsCompositeType() {
				kinds[definition.Name] = true
			}
		}
	}
	mutations := make(map[string]mutationSchema)
	for _, definition := range definitions[mutationType] {
		if definition.Kind != ast.Object {
			continue
		}
		for _, field := range definition.Fields {
			if _, exists := mutations[field.Name]; exists {
				return nil, fmt.Errorf("duplicate mutation field %s", field.Name)
			}
			mutation := mutationSchema{Description: strings.TrimSpace(strings.SplitN(strings.TrimSpace(field.Description), "\n", 2)[0])}
			if deprecated := field.Directives.ForName("deprecated"); deprecated != nil {
				mutation.Deprecated = true
				mutation.DeprecationReason = "No longer supported"
				if reason := deprecated.Arguments.ForName("reason"); reason != nil && reason.Value != nil {
					mutation.DeprecationReason = reason.Value.Raw
				}
			}
			if input := field.Arguments.ForName("input"); input != nil && input.Type != nil {
				mutation.InputType = input.Type.Name()
				for _, inputDefinition := range definitions[mutation.InputType] {
					if inputDefinition.Kind != ast.InputObject {
						continue
					}
					for _, inputField := range inputDefinition.Fields {
						if inputField.Type == nil {
							return nil, fmt.Errorf("input field %s.%s has no type", mutation.InputType, inputField.Name)
						}
						mutation.InputFields = append(mutation.InputFields, schemaInputField{Name: inputField.Name, Type: inputField.Type.String()})
						if inputField.Type.NamedType != "ID" || inputField.Type.Elem != nil || (inputField.Name != "id" && !strings.HasSuffix(inputField.Name, "Id")) {
							continue
						}
						kind := ""
						if prefix := strings.TrimSuffix(inputField.Name, "Id"); inputField.Name != "id" && prefix != "" {
							candidate := strings.ToUpper(prefix[:1]) + prefix[1:]
							if kinds[candidate] {
								kind = candidate
							}
						}
						mutation.IDFields = append(mutation.IDFields, schemaIDField{Name: inputField.Name, Kind: kind})
					}
				}
			}
			sort.Slice(mutation.InputFields, func(i, j int) bool { return mutation.InputFields[i].Name < mutation.InputFields[j].Name })
			sort.Slice(mutation.IDFields, func(i, j int) bool { return mutation.IDFields[i].Name < mutation.IDFields[j].Name })
			mutation.PrimaryID = primaryID(field.Name, mutation.IDFields)
			mutations[field.Name] = mutation
		}
	}
	if len(mutations) == 0 {
		return nil, fmt.Errorf("schema has no mutation fields")
	}
	return mutations, nil
}

func primaryID(mutation string, candidates []schemaIDField) string {
	best, length, tied := "", 0, false
	for _, candidate := range candidates {
		noun := strings.TrimSuffix(candidate.Name, "Id")
		if candidate.Name == "id" {
			noun = ""
		}
		if candidate.Kind != "" {
			noun = candidate.Kind
		}
		if noun == "" || !strings.Contains(strings.ToLower(mutation), strings.ToLower(noun)) {
			continue
		}
		if len(noun) > length {
			best, length, tied = candidate.Name, len(noun), false
		} else if len(noun) == length {
			tied = true
		}
	}
	if best != "" && !tied {
		return best
	}
	if len(candidates) == 1 {
		return candidates[0].Name
	}
	return ""
}

func readSchema(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	client := &http.Client{Timeout: 30 * time.Second}
	response, err := client.Get(publicSchemaURL)
	if err != nil {
		return nil, fmt.Errorf("fetch schema: %w", err)
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch schema: HTTP %s", response.Status)
	}
	return io.ReadAll(response.Body)
}
