// Command gen generates the REST route snapshot. It has no non-stdlib dependencies.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"time"
)

const sourcePath = "descriptions/api.github.com/api.github.com.json"

type schema struct {
	Ref   string   `json:"$ref"`
	Type  string   `json:"type"`
	OneOf []schema `json:"oneOf"`
	AnyOf []schema `json:"anyOf"`
}

type parameter struct {
	Ref    string `json:"$ref"`
	Name   string `json:"name"`
	In     string `json:"in"`
	Schema schema `json:"schema"`
}

type operation struct {
	ID         string      `json:"operationId"`
	Parameters []parameter `json:"parameters"`
	Tags       []string    `json:"tags"`
	Deprecated bool        `json:"deprecated"`
}

type document struct {
	Paths      map[string]map[string]json.RawMessage `json:"paths"`
	Components struct {
		Parameters map[string]parameter `json:"parameters"`
		Schemas    map[string]schema    `json:"schemas"`
	} `json:"components"`
}

func main() {
	ref := flag.String("ref", "", "full upstream commit SHA (required)")
	date := flag.String("date", "", "upstream commit date, YYYY-MM-DD (required)")
	spec := flag.String("spec", "", "local OpenAPI JSON instead of fetching the pinned revision")
	out := flag.String("out", "routes_gen.go", "generated Go file")
	flag.Parse()
	if err := generate(*ref, *date, *spec, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(ref, date, spec, out string) error {
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(ref) {
		return fmt.Errorf("-ref must be a full lowercase commit SHA")
	}
	if _, err := time.Parse("2006-01-02", date); err != nil {
		return fmt.Errorf("-date must be the upstream commit date: %w", err)
	}
	var data []byte
	var err error
	if spec != "" {
		data, err = os.ReadFile(spec)
	} else {
		client := http.Client{Timeout: 60 * time.Second}
		var resp *http.Response
		resp, err = client.Get("https://raw.githubusercontent.com/github/rest-api-description/" + ref + "/" + sourcePath)
		if err == nil {
			if resp.StatusCode != http.StatusOK {
				if err := resp.Body.Close(); err != nil {
					return fmt.Errorf("fetch OpenAPI: %s; close response: %w", resp.Status, err)
				}
				return fmt.Errorf("fetch OpenAPI: %s", resp.Status)
			}
			data, err = io.ReadAll(resp.Body)
			if closeErr := resp.Body.Close(); err == nil {
				err = closeErr
			}
		}
	}
	if err != nil {
		return fmt.Errorf("read OpenAPI: %w", err)
	}
	generated, count, err := render(data, ref, date)
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, generated, 0o644); err != nil {
		return err
	}
	fmt.Printf("generated %d REST operations from %s (%s)\n", count, ref, date)
	return nil
}

func render(data []byte, ref, date string) ([]byte, int, error) {
	var doc document
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, 0, fmt.Errorf("decode OpenAPI: %w", err)
	}
	if len(doc.Paths) == 0 {
		return nil, 0, fmt.Errorf("OpenAPI has no paths")
	}
	paths := make([]string, 0, len(doc.Paths))
	for path := range doc.Paths {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by go generate; DO NOT EDIT.\n// Source: github/rest-api-description %s\n// Commit: %s\n// Source date: %s\n\npackage rest\n\nvar generatedRoutes = []route{\n", sourcePath, ref, date)
	seen := make(map[string]bool)
	count := 0
	for _, path := range paths {
		item := doc.Paths[path]
		var inherited []parameter
		if raw, ok := item["parameters"]; ok {
			if err := json.Unmarshal(raw, &inherited); err != nil {
				return nil, 0, fmt.Errorf("%s parameters: %w", path, err)
			}
		}
		for _, method := range []string{"get", "head", "post", "put", "patch", "delete", "options", "trace", "connect"} {
			raw, ok := item[method]
			if !ok {
				continue
			}
			var op operation
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, 0, err
			}
			if op.ID == "" || seen[op.ID] {
				return nil, 0, fmt.Errorf("%s %s: empty or duplicate operationId %q", method, path, op.ID)
			}
			seen[op.ID] = true
			params := make(map[string]parameter)
			for _, p := range append(inherited[:len(inherited):len(inherited)], op.Parameters...) {
				if p.Ref != "" {
					name, ok := strings.CutPrefix(p.Ref, "#/components/parameters/")
					var exists bool
					p, exists = doc.Components.Parameters[name]
					if !ok || !exists || p.Ref != "" {
						return nil, 0, fmt.Errorf("%s: unsupported parameter reference", op.ID)
					}
				}
				if p.In == "path" {
					params[p.Name] = p
				}
			}
			fmt.Fprintf(&buf, "{method: %q, path: %q, operationID: %q, deprecated: %t, tags: []string{", strings.ToUpper(method), path, op.ID, op.Deprecated)
			for _, tag := range op.Tags {
				fmt.Fprintf(&buf, "%q,", tag)
			}
			buf.WriteString("}, parameters: []pathParameter{")
			for _, segment := range strings.Split(path, "/") {
				if !strings.ContainsAny(segment, "{}") {
					continue
				}
				if !strings.HasPrefix(segment, "{") || !strings.HasSuffix(segment, "}") || strings.Count(segment, "{") != 1 {
					return nil, 0, fmt.Errorf("%s: unsupported path segment %q", op.ID, segment)
				}
				name := strings.TrimSuffix(strings.TrimPrefix(segment, "{"), "}")
				p, ok := params[name]
				if !ok {
					return nil, 0, fmt.Errorf("%s: missing path parameter %s", op.ID, name)
				}
				types, err := doc.schemaTypes(p.Schema, 0)
				if err != nil {
					return nil, 0, fmt.Errorf("%s parameter %s: %w", op.ID, name, err)
				}
				slices.Sort(types)
				types = slices.Compact(types)
				fmt.Fprintf(&buf, "{name: %q, types: %q},", name, strings.Join(types, "|"))
			}
			buf.WriteString("}},\n")
			count++
		}
	}
	buf.WriteString("}\n")
	formatted, err := format.Source(buf.Bytes())
	return formatted, count, err
}

func (doc *document) schemaTypes(s schema, depth int) ([]string, error) {
	if depth > 20 {
		return nil, fmt.Errorf("recursive schema reference")
	}
	if s.Ref != "" {
		name, ok := strings.CutPrefix(s.Ref, "#/components/schemas/")
		referenced, exists := doc.Components.Schemas[name]
		if !ok || !exists {
			return nil, fmt.Errorf("unsupported schema reference %q", s.Ref)
		}
		return doc.schemaTypes(referenced, depth+1)
	}
	if s.Type == "string" || s.Type == "integer" {
		return []string{s.Type}, nil
	}
	var types []string
	for _, member := range append(s.OneOf[:len(s.OneOf):len(s.OneOf)], s.AnyOf...) {
		memberTypes, err := doc.schemaTypes(member, depth+1)
		if err != nil {
			return nil, err
		}
		types = append(types, memberTypes...)
	}
	if len(types) == 0 {
		return nil, fmt.Errorf("unsupported path parameter schema type %q", s.Type)
	}
	return types, nil
}
