// Command gen captures gh's real Cobra tree without executing command handlers.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"runtime/debug"
	"slices"
	"strings"

	"github.com/cli/cli/v2/internal/config"
	"github.com/cli/cli/v2/internal/telemetry"
	"github.com/cli/cli/v2/pkg/cmd/factory"
	"github.com/cli/cli/v2/pkg/cmd/root"
	"github.com/cli/cli/v2/pkg/iostreams"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return fmt.Errorf("missing Go build module provenance")
	}
	var version, sum string
	for _, dep := range info.Deps {
		if dep.Path == "github.com/cli/cli/v2" {
			if dep.Replace != nil || dep.Sum == "" {
				return fmt.Errorf("cli/cli must be a checksummed, unreplaced release")
			}
			version, sum = dep.Version, dep.Sum
		}
	}
	if version == "" {
		return fmt.Errorf("cli/cli module not found in build info")
	}

	home, err := os.MkdirTemp("", "ghok-native-gen-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(home)
	// No user aliases, extensions, alternate Cobra mode or feature/debug
	// environment may affect the snapshot. Only process-local state changes.
	for _, entry := range os.Environ() {
		key, _, _ := strings.Cut(entry, "=")
		if strings.HasPrefix(key, "GH_") || strings.HasPrefix(key, "GITHUB_") {
			if err := os.Unsetenv(key); err != nil {
				return err
			}
		}
	}
	for key, value := range map[string]string{
		"HOME": home, "GH_CONFIG_DIR": filepath.Join(home, "gh"),
		"XDG_CONFIG_HOME": filepath.Join(home, "config"),
		"XDG_DATA_HOME":   filepath.Join(home, "data"),
		"XDG_STATE_HOME":  filepath.Join(home, "state"),
		"XDG_CACHE_HOME":  filepath.Join(home, "cache"),
	} {
		if err := os.Setenv(key, value); err != nil {
			return err
		}
	}
	ios := iostreams.System()
	null, err := os.OpenFile(os.DevNull, os.O_RDWR, 0)
	if err != nil {
		return err
	}
	defer null.Close()
	ios.In, ios.Out, ios.ErrOut = null, null, null
	service := &telemetry.NoOpService{}
	f := factory.New(version, "", config.NewConfig, ios, "gh", service)
	cmd, err := root.NewCmdRoot(f, service, version, "")
	if err != nil {
		return err
	}
	// Cobra creates help and __complete lazily. An empty __complete request
	// fails MinimumNArgs(1) before pre-runs, Run or completion callbacks.
	cmd.SetArgs([]string{cobra.ShellCompRequestCmd})
	cmd.SetOut(io.Discard)
	cmd.SetErr(io.Discard)
	selected, err := cmd.ExecuteC()
	if err == nil || selected == nil || selected.Name() != cobra.ShellCompRequestCmd {
		return fmt.Errorf("unexpected Cobra completion initialization: %v", err)
	}

	type entry struct {
		command *cobra.Command
		path    string
	}
	var entries []entry
	var walk func(*cobra.Command, []string)
	walk = func(c *cobra.Command, paths []string) {
		c.InitDefaultHelpFlag()
		c.InitDefaultVersionFlag()
		for _, path := range paths {
			entries = append(entries, entry{c, path})
		}
		for _, child := range c.Commands() {
			names := append([]string{child.Name()}, child.Aliases...)
			var childPaths []string
			for _, parent := range paths {
				for _, name := range names {
					childPaths = append(childPaths, strings.TrimSpace(parent+" "+name))
				}
			}
			walk(child, childPaths)
		}
	}
	walk(cmd, []string{""})
	slices.SortFunc(entries, func(a, b entry) int { return strings.Compare(a.path, b.path) })
	aliases := make(map[string]string)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate ./internal/normalize/native; DO NOT EDIT.")
	fmt.Fprintf(&out, "// Upstream: github.com/cli/cli/v2 %s\n// Module sum: %s\n", version, sum)
	fmt.Fprintln(&out, "package native")
	fmt.Fprintln(&out, "var generatedCommands = map[string]commandMetadata{")
	canonicalCount, flagCount := 0, 0
	for _, e := range entries {
		c := e.command
		canonical := strings.TrimPrefix(c.CommandPath(), cmd.Name())
		canonical = strings.TrimSpace(canonical)
		// Default config's co is a real forwarding command, not a Cobra alias.
		if expansion := c.Annotations["gh:alias-expansion"]; expansion != "" {
			target, rest, err := cmd.Find(strings.Fields(expansion))
			if err != nil || len(rest) != 0 {
				return fmt.Errorf("cannot canonicalize built-in alias %q: %q", e.path, expansion)
			}
			canonical = strings.TrimSpace(strings.TrimPrefix(target.CommandPath(), cmd.Name()))
		}
		if e.path != canonical {
			aliases[e.path] = canonical
		} else {
			canonicalCount++
		}
		argsHint := ""
		if c.Args != nil {
			argsHint = runtime.FuncForPC(reflect.ValueOf(c.Args).Pointer()).Name()
		}
		fmt.Fprintf(&out, "%q: {canonicalPath: %q, hidden: %t, deprecated: %q, disableFlagParsing: %t, argsHint: %q,\n", e.path, canonical, c.Hidden, c.Deprecated, c.DisableFlagParsing, argsHint)
		if len(c.Annotations) > 0 {
			fmt.Fprintln(&out, "annotations: map[string]string{")
			keys := make([]string, 0, len(c.Annotations))
			for key := range c.Annotations {
				keys = append(keys, key)
			}
			slices.Sort(keys)
			for _, key := range keys {
				fmt.Fprintf(&out, "%q: %q,\n", key, c.Annotations[key])
			}
			fmt.Fprintln(&out, "},")
		}
		fmt.Fprintln(&out, "flags: []flagSpec{")
		// InitDefaultHelpFlag merges local and inherited persistent flags,
		// respecting local shadowing, exactly as Cobra does before parsing.
		c.Flags().VisitAll(func(flag *pflag.Flag) {
			short := byte(0)
			if flag.Shorthand != "" {
				short = flag.Shorthand[0]
			}
			fmt.Fprintf(&out, "{long: %q, short: %d, valueType: %q, noOptDefVal: %q, hidden: %t, deprecated: %q, shorthandDeprecated: %q},\n", flag.Name, short, flag.Value.Type(), flag.NoOptDefVal, flag.Hidden, flag.Deprecated, flag.ShorthandDeprecated)
			if e.path == canonical {
				flagCount++
			}
		})
		fmt.Fprintln(&out, "}},")
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var commandAliases = map[string]string{")
	for _, e := range entries {
		if canonical, ok := aliases[e.path]; ok {
			fmt.Fprintf(&out, "%q: %q,\n", e.path, canonical)
		}
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile("../registry_gen.go", formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("generated %d canonical commands (including root), %d alias paths, %d canonical flag records from gh %s\n", canonicalCount, len(aliases), flagCount, version)
	return nil
}
